# Draws the installer screens for a version into installer\piezas: the BMP pieces at 100, 125,
# 150 and 200 % and posiciones.iss, which reflex.iss includes. Both are committed, so building
# the installer only needs Inno Setup.
# Needs Python, Node 22 or later, Microsoft Edge and internet (Sora and Inter come from Google Fonts).
param([Parameter(Mandatory)][ValidatePattern('^\d+\.\d+\.\d+')][string]$Version)
$ErrorActionPreference = 'Stop'
$diseno = Join-Path $PSScriptRoot 'diseno'
$construido = Join-Path $diseno 'construido'
$destino = Join-Path $PSScriptRoot 'piezas'

python -I (Join-Path $diseno 'generar.py') $Version | Out-Null
if ($LASTEXITCODE) { throw 'generar.py ha fallado' }
$edge = @("${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe", "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe") |
    Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $edge) { throw 'Falta Microsoft Edge para dibujar el instalador' }
Remove-Item (Join-Path $construido 'piezas') -Recurse -Force -ErrorAction SilentlyContinue
node (Join-Path $diseno 'piezas.mjs') $edge $construido
if ($LASTEXITCODE) { throw 'piezas.mjs ha fallado' }

Add-Type -AssemblyName System.Drawing
Remove-Item $destino -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory $destino | Out-Null
foreach ($png in Get-ChildItem (Join-Path $construido 'piezas\*.png')) {
    $imagen = [System.Drawing.Image]::FromFile($png.FullName)
    $bmp = New-Object System.Drawing.Bitmap $imagen.Width, $imagen.Height, ([System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.ColorTranslator]::FromHtml('#0B0E1A'))
    $g.DrawImage($imagen, 0, 0, $imagen.Width, $imagen.Height)
    $g.Dispose()
    $bmp.Save((Join-Path $destino ($png.BaseName + '.bmp')), [System.Drawing.Imaging.ImageFormat]::Bmp)
    $bmp.Dispose(); $imagen.Dispose()
}
$posiciones = "; Generated by construir.ps1: do not edit.`r`n#define PiezasVersion `"$Version`"`r`n" +
    (Get-Content (Join-Path $construido 'posiciones.iss') -Raw)
[System.IO.File]::WriteAllText((Join-Path $destino 'posiciones.iss'), $posiciones)
"Instalador dibujado para la version ${Version}: $((Get-ChildItem "$destino\*.bmp").Count) piezas"
